  // Primary brand colors
  static const Color primary = Color(0xFF2563EB); // Royal Blue
  static const Color primaryDark = Color(0xFF1D4ED8);
  static const Color primaryLight = Color(0xFF60A5FA);
  static const Color primarySurface = Color(0xFFEFF6FF);

  // Secondary & Accents
  static const Color emerald = Color(0xFF22C55E); // Green accent
  static const Color emeraldLight = Color(0xFFDCFCE7);
  static const Color emeraldDark = Color(0xFF15803D);

  static const Color gold = Color(0xFFFACC15); // Yellow/gold accent
  static const Color goldLight = Color(0xFFFEF9C3);
  static const Color goldDark = Color(0xFFA16207);

  // Neutrals & Surfaces
  static const Color background = Color(0xFFF8FAFC);
  static const Color surface = Color(0xFFFFFFFF);
  static const Color card = Color(0xFFFFFFFF);
  static const Color border = Color(0xFFE2E8F0);
  static const Color divider = Color(0xFFE2E8F0);

  // Typography
  static const Color textPrimary = Color(0xFF0F172A);
  static const Color textSecondary = Color(0xFF475569);
  static const Color textMuted = Color(0xFF94A3B8);

  // Status colors
  static const Color error = Color(0xFFDC2626);
  static const Color errorSurface = Color(0xFFFEE2E2);

  static const Color warning = Color(0xFFF59E0B);
  static const Color warningSurface = Color(0xFFFEF3C7);

